@Composable
fun MyApplicationTheme(
    darkTheme: Boolean = true, // Default to sleek dark game theme
    dynamicColor: Boolean = false, // Keep tailored vibrant gaming palette
    content: @Composable () -> Unit
) {
    val colorScheme = if (darkTheme) DarkColorScheme else LightColorScheme
    MaterialTheme(
        colorScheme = colorScheme,
        typography = Typography,
        content = content
    )
}
